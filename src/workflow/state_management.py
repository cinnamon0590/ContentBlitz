"""Shared state and domain models for the ContentBlitz LangGraph workflow.

Design notes
------------
* ``ContentState`` is the single ``TypedDict`` shared by every node (the same
  pattern as the content-writer template: ``messages`` uses the ``add_messages``
  reducer so the conversation accumulates across turns).
* Artifacts (research, blog, LinkedIn post, image, report, quality) are stored in
  state as plain ``dict`` dumps of the Pydantic models below. Plain dicts
  serialize cleanly with every LangGraph checkpointer (memory or SQLite) and
  are easy for the Streamlit UI to render. Use ``Model.model_validate(d)`` to
  rehydrate.
* Every artifact carries a :class:`Provenance` block: where the information came
  from (sources), which model produced it, and how it is grounded.
* ``sources`` is the thread-wide source registry. Its reducer
  (:func:`merge_sources`) de-duplicates by URL and keeps citation ids stable
  across turns, so a follow-up blog reuses the ``[n]`` numbers of the research
  it builds on.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Annotated, Any, Literal, TypedDict
from urllib.parse import urlparse

from langchain_core.messages import AnyMessage
from langgraph.graph.message import add_messages
from pydantic import BaseModel, Field

Grounding = Literal["live_research", "cached_research", "model_knowledge_only"]

MODEL_KNOWLEDGE_LABEL = "Based on AI model knowledge — not verified against live sources."

Intent = Literal["research", "blog", "linkedin", "image", "report", "campaign", "general", "blocked"]

# Writing personas the brand voice can follow (learned from samples or chosen in Settings).
VOICE_ARCHETYPES: dict[str, str] = {
    "storyteller": "lead with a moment, a customer or a turning point; show, then tell",
    "conversational": "write like you talk to one person: contractions, short sentences, direct questions",
    "data-driven": "anchor every point in evidence and numbers from the sources; precise, measured claims",
    "educator": "explain step by step with clear examples and practical takeaways",
    "contrarian": "challenge a common belief with a clear thesis, then back it up",
}
EmojiLevel = Literal["none", "light", "heavy"]


def utc_now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


# --------------------------------------------------------------------------------------
# Sources & provenance
# --------------------------------------------------------------------------------------
class Source(BaseModel):
    """A single piece of retrieved evidence. ``id`` is the citation number ``[n]``."""

    id: int = 0
    title: str = ""
    url: str
    publisher: str = ""
    snippet: str = ""
    retrieved_at: str = Field(default_factory=utc_now)
    provider: str = ""  # serpapi | tavily | perplexity | cache
    used_in: list[str] = Field(default_factory=list)

    def model_post_init(self, __context: Any) -> None:
        if not self.publisher and self.url:
            self.publisher = urlparse(self.url).netloc.removeprefix("www.")


class Provenance(BaseModel):
    """Where an artifact's information came from and how it was produced."""

    sources: list[Source] = Field(default_factory=list)
    generated_by: str = ""  # e.g. "openai:gpt-4o"
    image_model: str | None = None
    grounding: Grounding = "model_knowledge_only"
    revision_count: int = 0
    created_at: str = Field(default_factory=utc_now)
    notes: list[str] = Field(default_factory=list)  # fallbacks used, warnings, cache age...

    @property
    def label(self) -> str:
        if self.grounding == "model_knowledge_only":
            return MODEL_KNOWLEDGE_LABEL
        if self.grounding == "cached_research":
            when = min((s.retrieved_at for s in self.sources), default=self.created_at)
            return f"Grounded in cached research (retrieved {when})."
        return f"Grounded in live web research ({len(self.sources)} sources)."

    def to_markdown(self) -> str:
        lines = ["## Sources & Provenance", "", f"_{self.label}_", ""]
        if self.sources:
            for s in sorted(self.sources, key=lambda x: x.id):
                title = s.title or s.publisher or s.url
                lines.append(
                    f"[{s.id}] [{title}]({s.url}) — {s.publisher} · via {s.provider or 'web'} · retrieved {s.retrieved_at}"
                )
            lines.append("")
        gen = f"Generated by {self.generated_by}" if self.generated_by else "Generated by AI"
        if self.image_model:
            gen += f"; image model {self.image_model}"
        lines.append(f"- {gen} on {self.created_at}; revisions: {self.revision_count}.")
        lines.extend(f"- {note}" for note in self.notes)
        lines.append("- AI-assisted content: review facts and claims before publishing.")
        return "\n".join(lines)



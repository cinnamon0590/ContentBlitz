# --------------------------------------------------------------------------------------
# Source registry reducer
# --------------------------------------------------------------------------------------
def normalize_url(url: str) -> str:
    return url.strip().rstrip("/").lower()


def merge_sources(left: list[dict] | None, right: list[dict] | None) -> list[dict]:
    """Reducer for ``ContentState.sources``.

    De-duplicates by URL, preserves existing ids, merges ``used_in`` and assigns
    the next free id to genuinely new sources.
    """
    merged: list[dict] = [dict(s) for s in (left or [])]
    by_url = {normalize_url(s["url"]): s for s in merged}
    next_id = max((s.get("id", 0) for s in merged), default=0) + 1
    for incoming in right or []:
        key = normalize_url(incoming["url"])
        if key in by_url:
            existing = by_url[key]
            existing["used_in"] = sorted(set(existing.get("used_in", [])) | set(incoming.get("used_in", [])))
            continue
        item = dict(incoming)
        if not item.get("id") or any(s.get("id") == item["id"] for s in merged):
            item["id"] = next_id
        next_id = max(next_id, item["id"]) + 1
        merged.append(item)
        by_url[key] = item
    return merged


class SourceRegistry:
    """Helper used by agents to register sources and obtain stable citation ids."""

    def __init__(self, existing: list[dict] | None = None):
        self._sources: list[dict] = merge_sources([], existing or [])

    def add(self, source: Source) -> Source:
        self._sources = merge_sources(self._sources, [source.model_dump()])
        key = normalize_url(source.url)
        stored = next(s for s in self._sources if normalize_url(s["url"]) == key)
        return Source.model_validate(stored)

    def mark_used(self, ids: list[int], artifact: str) -> None:
        for s in self._sources:
            if s["id"] in ids and artifact not in s.get("used_in", []):
                s["used_in"] = sorted([*s.get("used_in", []), artifact])

    def get(self, source_id: int) -> Source | None:
        for s in self._sources:
            if s["id"] == source_id:
                return Source.model_validate(s)
        return None

    def by_ids(self, ids: list[int]) -> list[Source]:
        return [src for i in ids if (src := self.get(i)) is not None]

    @property
    def urls(self) -> set[str]:
        return {normalize_url(s["url"]) for s in self._sources}

    def all(self) -> list[Source]:
        return [Source.model_validate(s) for s in self._sources]

    def dump(self) -> list[dict]:
        return [dict(s) for s in self._sources]


# --------------------------------------------------------------------------------------
# Graph state
# --------------------------------------------------------------------------------------
class ContentState(TypedDict, total=False):
    """State shared across all nodes. Persisted per ``thread_id`` by the checkpointer."""

    messages: Annotated[list[AnyMessage], add_messages]  # user-visible conversation (memory)
    # Working memory for the agent ↔ ToolNode loops. Kept separate so tool chatter never
    # pollutes the user-facing conversation; cleared when each agent finishes.
    agent_scratch: Annotated[list[AnyMessage], add_messages]
    user_input: str  # the (sanitised) latest user message
    route: Intent  # initial routing decision for this turn
    next_after_research: str  # post-research routing decision
    request: dict  # ContentRequest dump
    pending_formats: list[str]  # campaign queue, e.g. ["blog", "linkedin", "image"]
    brand: dict  # BrandProfile dump

    research: dict  # ResearchReport dump
    blog: dict  # BlogPost dump
    linkedin: dict  # LinkedInPost dump
    image: dict  # ImageAsset dump
    images: list[dict]  # history of ImageAsset dumps for the gallery
    report: dict  # StrategyReport dump
    quality: dict  # {"blog": QualityReport dump, "linkedin": ...}
    sources: Annotated[list[dict], merge_sources]  # thread-wide source registry

    revision_count: int
    revision_feedback: str  # quality-gate suggestions handed back to the writer
    quality_target: str  # which artifact the quality gate should check next
    outputs_this_turn: list[str]
    final_response: str
    usage: dict  # CostTracker summary for the latest turn
    errors: list[str]
    warnings: list[str]
    tool_iterations: int
    deep_research_calls: int
